const authService = require('./auth.service');

const register = async (req, res, next) => {
  try {
    const ip = req.ip || req.connection.remoteAddress;
    const result = await authService.register(req.body, ip);
    res.status(201).json({ success: true, data: result });
  } catch (error) {
    if (error.message === 'User already exists') {
      return res.status(400).json({ success: false, message: error.message });
    }
    next(error);
  }
};

const login = async (req, res, next) => {
  try {
    const ip = req.ip || req.connection.remoteAddress;
    const result = await authService.login(req.body.email, req.body.password, ip);
    res.status(200).json({ success: true, data: result });
  } catch (error) {
    if (error.message.includes('Invalid email') || error.message.includes('blocked') || error.message.includes('Too many')) {
      return res.status(401).json({ success: false, message: error.message });
    }
    next(error);
  }
};

const firebaseLogin = async (req, res, next) => {
  try {
    const ip = req.ip || req.connection.remoteAddress;
    const result = await authService.firebaseLogin(req.body.idToken, ip);
    res.status(200).json({ success: true, data: result });
  } catch (error) {
    if (error.message.includes('blocked')) {
      return res.status(401).json({ success: false, message: error.message });
    }
    next(error);
  }
};

const googleAuthCallback = async (req, res, next) => {
  try {
    const ip = req.ip || req.connection.remoteAddress;
    // req.user is generated by passport GoogleStrategy
    const result = await authService.googleLogin(req.user, ip);
    
    // During a full-flow OAuth (browser), we typically redirect down to the client app dropping the token
    const url = process.env.CLIENT_URL || 'http://localhost:3000';
    res.redirect(`${url}/login/success?token=${result.accessToken}`);
  } catch (error) {
    const url = process.env.CLIENT_URL || 'http://localhost:3000';
    res.redirect(`${url}/login/error`);
  }
};

const forgotPassword = async (req, res, next) => {
  try {
    const result = await authService.forgotPassword(req.body.email);
    res.status(200).json({ success: true, message: result.message });
  } catch (error) {
    res.status(400).json({ success: false, message: error.message });
  }
};

const verifyOtp = async (req, res, next) => {
  try {
    const result = await authService.verifyOtp(req.body.email, req.body.code);
    res.status(200).json({ success: true, message: result.message });
  } catch (error) {
    res.status(400).json({ success: false, message: error.message });
  }
};

const resetPassword = async (req, res, next) => {
  try {
    const result = await authService.resetPassword(req.body.email, req.body.code, req.body.newPassword);
    res.status(200).json({ success: true, message: result.message });
  } catch (error) {
    res.status(400).json({ success: false, message: error.message });
  }
};

const refresh = async (req, res, next) => {
  try {
    const result = await authService.refreshTokens(req.body.refreshToken);
    res.status(200).json({ success: true, data: result });
  } catch (error) {
    return res.status(401).json({ success: false, message: error.message });
  }
};

const logout = async (req, res, next) => {
  try {
    const authHeader = req.header('Authorization');
    const accessToken = authHeader ? authHeader.replace('Bearer ', '') : null;
    const { refreshToken } = req.body || {};

    await authService.logout(req.user.id, accessToken, refreshToken);
    res.status(200).json({ success: true, message: 'Logged out successfully' });
  } catch (error) {
    next(error);
  }
};

module.exports = {
  register,
  login,
  firebaseLogin,
  googleAuthCallback,
  forgotPassword,
  verifyOtp,
  resetPassword,
  refresh,
  logout
};
