const usersService = require('./users.service');

const getProfile = async (req, res, next) => {
  try {
    const user = await usersService.getProfile(req.user.id);
    res.status(200).json({ success: true, data: user });
  } catch (error) {
    if (error.message === 'User not found') return res.status(404).json({ success: false, message: error.message });
    next(error);
  }
};

const updateProfile = async (req, res, next) => {
  try {
    const user = await usersService.updateProfile(req.user.id, req.body);
    res.status(200).json({ success: true, data: user });
  } catch (error) {
    next(error);
  }
};

const changePassword = async (req, res, next) => {
  try {
    const result = await usersService.changePassword(req.user.id, req.body.oldPassword, req.body.newPassword);
    res.status(200).json({ success: true, message: result.message });
  } catch (error) {
    res.status(400).json({ success: false, message: error.message });
  }
};

const uploadAvatar = async (req, res, next) => {
  try {
    if (!req.file) {
      return res.status(400).json({ success: false, message: 'No file uploaded' });
    }
    // req.file.path contains the URL generated by Cloudinary
    const user = await usersService.uploadAvatar(req.user.id, req.file.path);
    res.status(200).json({ success: true, data: user });
  } catch (error) {
    next(error);
  }
};

const updateFCMToken = async (req, res, next) => {
  try {
    const result = await usersService.updateFCMToken(req.user.id, req.body.fcmToken);
    res.status(200).json({ success: true, message: result.message });
  } catch (error) {
    next(error);
  }
};

const { getPaginationParams } = require('../../utils/paginate');

const getAllUsers = async (req, res, next) => {
  try {
    const { page, limit } = getPaginationParams(req.query);
    const result = await usersService.getAllUsers({ ...req.query, page, limit });
    res.status(200).json({ success: true, ...result });
  } catch (error) {
    next(error);
  }
};

const blockUser = async (req, res, next) => {
  try {
    const result = await usersService.blockUser(req.user.id, req.params.id);
    res.status(200).json({ success: true, message: result.message });
  } catch (error) {
    res.status(400).json({ success: false, message: error.message });
  }
};

const submitVerification = async (req, res, next) => {
  try {
    if (!req.file) {
      return res.status(400).json({ success: false, message: 'No document uploaded' });
    }
    const user = await usersService.submitVerification(req.user.id, req.file.path);
    res.status(200).json({ success: true, message: 'Verification submitted', data: user });
  } catch (error) {
    next(error);
  }
};

const getPublicProfile = async (req, res, next) => {
  try {
    const user = await usersService.getPublicProfile(req.params.id);
    res.status(200).json({ success: true, data: user });
  } catch (error) {
    if (error.message === 'User not found') return res.status(404).json({ success: false, message: error.message });
    next(error);
  }
};

module.exports = {
  getProfile, updateProfile, changePassword, uploadAvatar, updateFCMToken, getAllUsers, blockUser, submitVerification, getPublicProfile
};
